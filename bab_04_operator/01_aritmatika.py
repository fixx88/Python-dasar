# BAB 04 - Operator Aritmatika

print("7 + 3  =", 7 + 3)      # Penjumlahan
print("7 - 3  =", 7 - 3)      # Pengurangan
print("7 * 3  =", 7 * 3)      # Perkalian
print("7 / 3  =", 7 / 3)      # Pembagian
print("7 // 3 =", 7 // 3)     # Pembagian bulat
print("7 % 3  =", 7 % 3)      # Modulus (sisa)
print("7 ** 3 =", 7 ** 3)     # Pangkat

# Urutan operasi: ( )  >  **  >  * / // %  >  + -
print("2 + 3 * 4 ** 2 =", 2 + 3 * 4 ** 2)   # 50
