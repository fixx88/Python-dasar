# BAB 02 - Empat Tipe Data Dasar: int, float, str, bool

print(10, -7, 2026)
print(type(10))          # <class 'int'>

print(3.14, -0.5)
print(type(3.14))        # <class 'float'>

print("Halo", 'A')
print(type("A"))         # <class 'str'>

print(True, False)
print(type(True))        # <class 'bool'>

# Nilai kosong ditulis None
kosong = None
print(kosong, type(kosong))
